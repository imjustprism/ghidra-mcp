def catalog_names() -> list[str]:
    lines = TOOLS_RS.read_text(encoding="utf-8").splitlines()
    names: list[str] = []
    for i, line in enumerate(lines):
        if "#[tool(" not in line:
            continue
        for j in range(i, min(i + 25, len(lines))):
            m = re.match(r"\s*async fn (\w+)", lines[j])
            if m:
                names.append(m.group(1))
                break
    return names


