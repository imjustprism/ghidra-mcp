def main() -> None:
    names = catalog_names()
    assigned: list[str] = [t for tools in CATEGORIES.values() for t in tools]
    missing = set(names) - set(assigned)
    extra = set(assigned) - set(names)
    dups = sorted({t for t in assigned if assigned.count(t) > 1})
    if missing or extra or dups:
        raise SystemExit(f"category mismatch missing={sorted(missing)} extra={sorted(extra)} dups={dups}")
    for t in names:
        if t not in PURPOSES:
            raise SystemExit(f"missing purpose for {t}")

    n = len(names)
    out: list[str] = [
        "## Tools",
        "",
        f"**{n} tools total.**",
        "",
        "Common conventions on most paginated read tools:",
        "",
        "- **fmt** — `tsv` (default), `csv`, `json`, or `verbose`",
        "- **offset** / **limit** — pagination",
        "- **program** — open program name or sha256 (otherwise the active program)",
        "",
    ]
    for cat, tools in CATEGORIES.items():
        out.append("<details>")
        out.append(f"<summary><b>{cat}</b> ({len(tools)})</summary>")
        out.append("")
        out.append("| tool | purpose |")
        out.append("| --- | --- |")
        for t in tools:
            out.append(f"| `{t}` | {PURPOSES[t]} |")
        out.append("")
        out.append("</details>")
        out.append("")

    out.append(
        "> Live attach and Lua helpers are powerful. They require an attached process "
        "and, for `lua_exec`, target-specific function addresses when built-in example defaults do not match."
    )
    out.append("")

    section = "\n".join(out)
    readme = README.read_text(encoding="utf-8")
    start = readme.index("## Tools")
    end = readme.index("\n## Prompts")
    README.write_text(readme[:start] + section + "\n" + readme[end + 1 :], encoding="utf-8", newline="\n")
    print(f"rewrote Tools section ({n} tools)")


if __name__ == "__main__":
    main()
